#using lambda keyword
add= lambda num : num+4
print (add(6))

#Using def         

def add(num):
    return num+4
print (add(6))

def sub(num):
    return num-4
print (sub(6))

def mul(num):
    return num*4
print (mul(6))

def div(num):
    return num/4
print (div(6))

def mod(num):
    return num%4
print (mod(6))

